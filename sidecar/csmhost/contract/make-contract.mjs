#!/usr/bin/env node
// Writes csm-host-contract.json, the numbers both sides of the plug-in host's protocol are held to
// (REQ-GAP-25). They are worked out here from the mock's written formulas, with no
// code of the mock, the host or the sidecar, so a run that matches is a real check on the path
// through all three: the Rust suite (tests/csmhost.rs) and the e2e spec (26-csmhost.spec.js) read
// this file and compare.
//
//   node sidecar/csmhost/contract/make-contract.mjs

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const A = 6378137.0;
const B = 6356752.314245179;
const E2 = 1 - (B * B) / (A * A);
const RAD = Math.PI / 180;

const isd = { lat0: 39.75, lon0: -105.2, gsd: 2.5, lines: 4000, samples: 6000, tilt: 0.4 };
const [sl, cl, so, co] = [Math.sin(isd.lat0 * RAD), Math.cos(isd.lat0 * RAD), Math.sin(isd.lon0 * RAD), Math.cos(isd.lon0 * RAD)];
const N0 = A / Math.sqrt(1 - E2 * sl * sl);
const ref = [N0 * cl * co, N0 * cl * so, N0 * (1 - E2) * sl];
const east = [-so, co, 0];
const north = [-sl * co, -sl * so, cl];
const up = [cl * co, cl * so, sl];
const dot = (a, b) => a[0] * b[0] + a[1] * b[1] + a[2] * b[2];
const sub = (a, b) => [a[0] - b[0], a[1] - b[1], a[2] - b[2]];

function geodeticToEcef(lat, lon, h) {
  const [s, c, ss, cc] = [Math.sin(lat * RAD), Math.cos(lat * RAD), Math.sin(lon * RAD), Math.cos(lon * RAD)];
  const N = A / Math.sqrt(1 - E2 * s * s);
  return [(N + h) * c * cc, (N + h) * c * ss, (N * (1 - E2) + h) * s];
}

function height(p) {
  const r = Math.hypot(p[0], p[1]);
  let lat = Math.atan2(p[2], r * (1 - E2));
  for (let i = 0; i < 50; i++) {
    const s = Math.sin(lat);
    const N = A / Math.sqrt(1 - E2 * s * s);
    lat = Math.atan2(p[2] + E2 * N * s, r);
  }
  const s = Math.sin(lat);
  const N = A / Math.sqrt(1 - E2 * s * s);
  return Math.abs(lat) < 1.5 ? r / Math.cos(lat) - N : p[2] / s - N * (1 - E2);
}

function g2i(p) {
  const d = sub(p, ref);
  return [isd.lines / 2 - dot(d, north) / isd.gsd, isd.samples / 2 + (dot(d, east) + isd.tilt * dot(d, up)) / isd.gsd];
}

function i2g(line, samp, h) {
  const n = (isd.lines / 2 - line) * isd.gsd;
  const e0 = (samp - isd.samples / 2) * isd.gsd;
  let u = h;
  let p;
  for (let i = 0; i < 100; i++) {
    const e = e0 - isd.tilt * u;
    p = [0, 1, 2].map((k) => ref[k] + e * east[k] + n * north[k] + u * up[k]);
    u += h - height(p);
  }
  return p;
}

const grounds = [
  [39.75, -105.2, 0],
  [39.752, -105.19, 1650.5],
  [39.74, -105.215, 2300],
  [39.761, -105.181, -40],
  [39.733, -105.206, 4000],
].map(([a, b, h]) => geodeticToEcef(a, b, h));
const images = [
  [2000, 3000, 0],
  [120.25, 5880.75, 1800],
  [3890.5, 44.5, 2500.5],
  [1, 1, -100],
  [2750, 4100, 3333],
];

const contract = {
  title: 'GIS Workbench CSM plug-in host: protocol contract',
  note: 'Generated by make-contract.mjs from the formulas in sidecar/csmhost/mock/mock_plugin.cpp. Not a statement about any real plug-in.',
  protocol: 1,
  isd,
  model: { name: 'GWB_MOCK_ORTHO', plugin: 'GWB mock plug-in', csm_major: 3, csm_minor: 0, sensor_type: 'EO', sensor_mode: 'FRAME' },
  g2i: { points: grounds, expect: grounds.map(g2i), tolerance_px: 1e-6 },
  i2g: { points: images, expect: images.map(([l, s, h]) => i2g(l, s, h)), tolerance_m: 1e-3 },
  partials: {
    ground: grounds[1],
    expect: { ground: [...north.map((v) => -v / isd.gsd), ...[0, 1, 2].map((k) => (east[k] + isd.tilt * up[k]) / isd.gsd)], sensor: [[1, 0], [0, 1]] },
    tolerance: 1e-12,
  },
  covariance: { image: [100, 200], expect: { unmodeled: [0.01, 0.002, 0.04], parameters: 2, covariance: [0.25, 0.05, 0.05, 0.25] } },
};

writeFileSync(join(dirname(fileURLToPath(import.meta.url)), 'csm-host-contract.json'), `${JSON.stringify(contract, null, 1)}\n`);
console.log('wrote csm-host-contract.json');
