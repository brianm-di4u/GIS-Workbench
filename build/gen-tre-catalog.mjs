// Compile Research/data/nitf-tre-catalog.json into the compact line format that gw-parse
// embeds (crates/gw-parse/data/tre-catalog.txt). Descriptions are dropped; structure kept.
//
//   T <NAME> <length|*> <priority>     start of a TRE
//   F <NAME> <size> <type>             field; size = int | $FIELD (value of) | * (rest of TRE)
//   L <NAME> <repeat-expr>             loop start (repeat: int, field name or arithmetic)
//   I <condition>                      conditional block start
//   E                                  end of loop / conditional
// Types: s string, i integer, r real, u unsigned big-endian binary, f float32 BE, b bytes.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, '..', 'Research', 'data', 'nitf-tre-catalog.json');
const out = join(root, 'crates', 'gw-parse', 'data', 'tre-catalog.txt');

const TYPE = {
  string: 's', 'ISO8859-1': 's', integer: 'i', real: 'r', bitmask: 'u',
  UnsignedInt_BigEndian: 'u', binary_u1: 'u', binary_u4: 'u', binary_u8: 'u',
  IEEE754_Float32_BigEndian: 'f', bytes: 'b',
};

const clean = (s) => String(s).replace(/\s+/g, ' ').trim();

function size(f) {
  const s = f.size;
  if (typeof s === 'number') return String(s);
  const t = clean(s);
  if (/^\d+$/.test(t)) return t;
  if (t === 'variable' || t === 'TREL.to_i') return '*';
  let m = /^value of (\w+)$/.exec(t) || /^(\w+)\.to_i$/.exec(t) || /^(\w+)$/.exec(t);
  if (m) return '$' + m[1];
  return '*';
}

function emit(fields, lines) {
  for (const f of fields) {
    if (f.loop !== undefined) {
      lines.push(`L ${f.loop} ${clean(f.repeat).replace(/\.to_i/g, '')}`);
      emit(f.fields, lines);
      lines.push('E');
    } else if (f.if !== undefined) {
      lines.push(`I ${clean(f.if)}`);
      emit(f.fields, lines);
      lines.push('E');
    } else {
      const ty = TYPE[f.type] ?? 's';
      lines.push(`F ${f.name} ${size(f)} ${ty}`);
    }
  }
}

const cat = JSON.parse(readFileSync(src, 'utf8'));
const lines = [`# generated by build/gen-tre-catalog.mjs from ${cat.version ?? '?'} (${cat.tres.length} TREs); do not edit`];
for (const t of cat.tres) {
  const len = typeof t.length === 'number' ? t.length : '*';
  lines.push(`T ${t.name} ${len} ${t.priority ?? 'COULD'}`);
  emit(t.fields, lines);
}
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, lines.join('\n') + '\n');
console.log(`tre-catalog: ${cat.tres.length} TREs, ${lines.length} lines → ${out}`);
