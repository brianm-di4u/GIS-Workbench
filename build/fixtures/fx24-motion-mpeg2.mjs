// FX-24 motion, MPEG-2 part (REQ-GAP-48, S-58): small MPEG-2 test streams for the app's own
// MPEG-2 decoder, made with ffmpeg from the gw-te environment (test generation only; ffmpeg is
// never bundled):
//
//   mpeg2_i576_klv.ts  interlaced 720×576 (field DCT and field motion compensation, alternate scan,
//                      intra VLC table B-15, 10-bit intra DC), 4 s, with the FX-21 ST 0601 KLV
//                      stream copied from fixtures/fx21/video/mpeg2_ts_klv.ts
//   mpeg2_fields.ts    field pictures (I/P, P/P and B/B field pairs, 16×8 and dual-prime
//                      prediction, concealment vectors, frame pictures between): the stream the
//                      gw-codec test generator writes (crates/gw-codec/src/mpeg2v.rs `fieldgen`,
//                      seed 7; ffmpeg's encoder writes no field pictures), put in MPEG-TS
//   mpeg2_422.ts       4:2:2 Profile (not Main Profile): the app's decoder refuses it, so the
//                      player offers the sidecar transcode
//
// mpeg2_truth.json records each file's frame count, size and the MD5 of every frame as ffmpeg
// decodes it (`-idct simple`, I420), for tests/unit/mpeg2v.test.js (bit-exact comparison).
//
//   node build/fixtures/fx24-motion-mpeg2.mjs

import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync, readFileSync, existsSync, rmSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { tool } from './fx21/video.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = join(ROOT, 'fixtures', 'fx24', 'motion');
const KLV_SRC = join(ROOT, 'fixtures', 'fx21', 'video', 'mpeg2_ts_klv.ts');
const TMP = process.env.GW_TMP ?? join(tmpdir(), 'gw-fx24-mpeg2');
mkdirSync(OUT, { recursive: true });
mkdirSync(TMP, { recursive: true });

const ff = (args) => execFileSync(tool('ffmpeg'), ['-hide_banner', '-loglevel', 'error', '-y', ...args], { stdio: ['ignore', 'inherit', 'inherit'] });
const p = (n) => join(OUT, n);

// 1. Interlaced 576i with the MPEG-2 coding tools ffmpeg's encoder has, KLV copied.
ff(['-t', '4', '-i', KLV_SRC, '-map', '0:v', '-map', '0:d', '-vf', 'scale=720:576,setfield=tff', '-c:v', 'mpeg2video', '-b:v', '2500k', '-g', '12', '-bf', '2', '-flags', '+ilme+ildct', '-alternate_scan', '1', '-intra_vlc', '1', '-dc', '10', '-c:d', 'copy', '-f', 'mpegts', p('mpeg2_i576_klv.ts')]);

// 2. Field pictures from the gw-codec generator.
const gen = join(TMP, 'fieldgen');
execFileSync('cargo', ['test', '--release', '-p', 'gw-codec', '--lib', 'fieldgen', '--', '--nocapture'], { cwd: join(ROOT, 'crates'), env: { ...process.env, GW_FFMPEG: tool('ffmpeg'), GW_MPEG2_GEN: gen }, stdio: ['ignore', 'inherit', 'inherit'] });
ff(['-fflags', '+genpts', '-r', '25', '-i', join(gen, 'fieldgen_7.m2v'), '-c:v', 'copy', '-f', 'mpegts', p('mpeg2_fields.ts')]);

// 3. 4:2:2 Profile.
ff(['-f', 'lavfi', '-i', 'testsrc2=size=352x288:rate=25', '-t', '1', '-c:v', 'mpeg2video', '-pix_fmt', 'yuv422p', '-b:v', '1500k', '-f', 'mpegts', p('mpeg2_422.ts')]);

// Truth: ffmpeg's frames (I420, simple IDCT), one MD5 each.
const truth = { generator: 'build/fixtures/fx24-motion-mpeg2.mjs', ffmpeg: execFileSync(tool('ffmpeg'), ['-version'], { encoding: 'utf8' }).split('\n')[0].trim(), files: {} };
for (const n of ['mpeg2_i576_klv.ts', 'mpeg2_fields.ts']) {
  const probe = JSON.parse(execFileSync(tool('ffprobe'), ['-v', 'error', '-select_streams', 'v:0', '-show_entries', 'stream=width,height,field_order,profile', '-of', 'json', p(n)], { encoding: 'utf8' })).streams[0];
  const yuv = join(TMP, `${n}.yuv`);
  ff(['-idct', 'simple', '-i', p(n), '-map', '0:v:0', '-f', 'rawvideo', '-pix_fmt', 'yuv420p', yuv]);
  const raw = readFileSync(yuv);
  const fsz = probe.width * probe.height + 2 * Math.ceil(probe.width / 2) * Math.ceil(probe.height / 2);
  const md5 = [];
  for (let k = 0; k + fsz <= raw.length; k += fsz) md5.push(createHash('md5').update(raw.subarray(k, k + fsz)).digest('hex'));
  rmSync(yuv);
  truth.files[n] = { width: probe.width, height: probe.height, fieldOrder: probe.field_order, profile: probe.profile, frames: md5.length, md5 };
}
truth.files['mpeg2_422.ts'] = { profile: '4:2:2', native: false };
writeFileSync(p('mpeg2_truth.json'), JSON.stringify(truth, null, 1));
const sha = (n) => createHash('sha256').update(readFileSync(p(n))).digest('hex');
const src = existsSync(p('SOURCE.txt')) ? readFileSync(p('SOURCE.txt'), 'utf8') : '';
const block = `\nfixtures/fx24/motion MPEG-2 files (REQ-GAP-48): generated by build/fixtures/fx24-motion-mpeg2.mjs with ffmpeg (gw-te environment) and the gw-codec field-picture test generator.\nmpeg2_i576_klv.ts video re-encoded from fixtures/fx21/video/mpeg2_ts_klv.ts (generated test data), its KLV copied.\nLicence: generated test data of this repository (no third-party content).\n${['mpeg2_i576_klv.ts', 'mpeg2_fields.ts', 'mpeg2_422.ts'].map((n) => `${n} sha256 ${sha(n)}`).join('\n')}\n`;
writeFileSync(p('SOURCE.txt'), src.replace(/\nfixtures\/fx24\/motion MPEG-2 files[\s\S]*$/, '') + block);
console.log(`fx24 motion MPEG-2 fixtures → ${OUT}`);
