// FX-24 GeoPDF oracle fixtures (REQ-GAP-66): GeoPDFs written by GDAL's PDF driver from FX-12
// (fixtures/fx12/fx12.geojson: polygons with holes, multi-parts, lines, points, Arabic, Cyrillic
// and CJK attribute values) in several projections, with and without stream compression, and a
// raster page with vector layers over a NAIP crop; plus GDAL's own read-back of each file as
// GeoJSON in the file's CRS (the oracle the reader is compared with).
//
//   node build/fixtures/fx24-geopdf.mjs        (GW_GDAL_BIN: GDAL's bin folder; test-time only)
//
// GDAL never ships (OSGeo4W, E:\gwb-sidecar-deps); the fixtures it writes are small and checked in.
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync, existsSync, rmSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, resolve } from 'node:path';

const BIN = process.env.GW_GDAL_BIN ?? 'E:/gwb-sidecar-deps/osgeo4w/root/bin';
const ROOT = resolve(BIN, '..');
const env = { ...process.env, PATH: `${BIN};${process.env.PATH}`, GDAL_DATA: join(ROOT, 'apps/gdal/share/gdal'), PROJ_DATA: join(ROOT, 'share/proj'), PROJ_LIB: join(ROOT, 'share/proj') };
const run = (cmd, args) => execFileSync(join(BIN, `${cmd}.exe`), args, { env, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
const OUT = resolve('fixtures/fx24/geopdf');
const TMP = process.env.GW_GEOPDF_TMP ?? 'E:/gwb24/geopdf/tmp';
mkdirSync(OUT, { recursive: true });
mkdirSync(TMP, { recursive: true });
const FX12 = resolve('fixtures/fx12/fx12.geojson');
const NAIP = resolve('..', 'TE-corpus', 'naip-ca-m3812157-sw-2022', 'm_3812157_sw_10_060_20220519.tif');

const files = [];
function vector(name, srs, extra = []) {
  const f = join(OUT, `${name}.pdf`);
  if (existsSync(f)) rmSync(f);
  run('ogr2ogr', ['-f', 'PDF', '-t_srs', srs, ...extra, f, FX12]);
  files.push(f);
}
// Projected (transverse Mercator, Lambert conformal conic in US feet, Albers, Mercator) and geographic.
vector('gdal_fx12_utm11n_plain', 'EPSG:32611', ['-dsco', 'STREAM_COMPRESS=NONE']);
vector('gdal_fx12_utm11n', 'EPSG:32611');
vector('gdal_fx12_ca5_ftus', 'EPSG:2229');
vector('gdal_fx12_albers', 'EPSG:5070');
vector('gdal_fx12_merc', 'EPSG:3857');
vector('gdal_fx12_wgs84', 'EPSG:4326');
// No attributes: GDAL writes no structure tree, so the layer is read from its optional content.
vector('gdal_fx12_utm11n_noattr', 'EPSG:32611', ['-dsco', 'OGR_WRITE_ATTRIBUTES=NO']);

// Raster page (a 400 × 300 NAIP crop, UTM 10N NAD83) with FX-12 moved onto it as vector layers.
if (existsSync(NAIP)) {
  const crop = join(TMP, 'naip_crop.tif');
  run('gdal_translate', ['-q', '-srcwin', '3946', '5141', '400', '300', '-b', '1', '-b', '2', '-b', '3', NAIP, crop]);
  const info = JSON.parse(run('gdalinfo', ['-json', crop]));
  const [lon, lat] = info.wgs84Extent.coordinates[0].reduce((s, c, i, a) => (i < a.length - 1 ? [s[0] + c[0] / (a.length - 1), s[1] + c[1] / (a.length - 1)] : s), [0, 0]);
  const fc = JSON.parse(readFileSync(FX12, 'utf8'));
  const shift = (c) => (typeof c[0] === 'number' ? [c[0] - -116.4993 + lon, c[1] - 34.5004 + lat, ...c.slice(2)] : c.map(shift));
  for (const f of fc.features) f.geometry.coordinates = shift(f.geometry.coordinates);
  const moved = join(TMP, 'fx12_on_naip.geojson');
  writeFileSync(moved, JSON.stringify(fc));
  const utm = join(TMP, 'fx12_on_naip_utm10.geojson');
  if (existsSync(utm)) rmSync(utm);
  run('ogr2ogr', ['-f', 'GeoJSON', '-t_srs', 'EPSG:26910', utm, moved]);
  const f = join(OUT, 'gdal_naip_fx12.pdf');
  if (existsSync(f)) rmSync(f);
  run('gdal_translate', ['-q', '-of', 'PDF', '-co', 'COMPRESS=JPEG', '-co', 'JPEG_QUALITY=80', '-co', `OGR_DATASOURCE=${utm}`, '-co', 'OGR_DISPLAY_FIELD=name', '-co', 'LAYER_NAME=NAIP 2022', crop, f]);
  files.push(f);
}

// GDAL's read-back of every file (the oracle): GeoJSON in the file's CRS.
const lines = [
  'fixtures/fx24/geopdf: GeoPDF oracle fixtures (REQ-GAP-66), generated by build/fixtures/fx24-geopdf.mjs',
  `with GDAL ${run('gdalinfo', ['--version']).trim()} (OSGeo4W, test-time only) from fixtures/fx12/fx12.geojson (generated test data)`,
  'and, for gdal_naip_fx12.pdf, a 400 x 300 crop of USDA NAIP m_3812157_sw_10_060_20220519.tif (public domain).',
  'Each <name>_gdal.geojson is GDAL\'s own read-back of <name>.pdf (ogr2ogr -f GeoJSON), coordinates in the file\'s CRS.',
  'Licence: generated test data of this repository; NAIP public domain.',
];
for (const f of files) {
  const gj = f.replace(/\.pdf$/, '_gdal.geojson');
  if (existsSync(gj)) rmSync(gj);
  run('ogr2ogr', ['-f', 'GeoJSON', '-lco', 'RFC7946=NO', '-lco', 'COORDINATE_PRECISION=6', gj, f]);
  for (const x of [f, gj]) lines.push(`${x.split(/[\\/]/).pop()} sha256 ${createHash('sha256').update(readFileSync(x)).digest('hex')}`);
}
writeFileSync(join(OUT, 'SOURCE.txt'), `${lines.join('\n')}\n`);
console.log(`${files.length} GeoPDFs in ${OUT}`);
