// Generate the theme CSS from app/src/data/ui-tokens.json (REQ-UI-12). Every colour, size
// and font in the chrome comes from these custom properties; a GC correction is a data
// change in the JSON, not a code change.
//   colors.<a.b>              → --c-a-b       (GXP-grey default, [data-theme="grey"])
//   colorsDarkDerived.<a.b>   → --c-a-b       under [data-theme="dark"]
//   colorsPrintDerived.<a.b>  → --c-a-b       under [data-theme="print"]
//   sizes.<name>.value        → --s-<name>
//   fonts.<name>              → --f-<name> (family), --fs-<name> (size), --fw-<name> (weight)

import { readFileSync } from 'node:fs';

const v = (k) => k.replace(/\./g, '-');

export function tokensCss(path) {
  const t = JSON.parse(readFileSync(path, 'utf8'));
  const base = ['--ui-scale:1'];
  // UI scale preference (REQ-UI-17): every px size token scales with --ui-scale.
  const sc = (val) => (/^-?\d+(\.\d+)?px$/.test(String(val)) ? `calc(${val} * var(--ui-scale))` : val);
  for (const [k, c] of Object.entries(t.colors)) base.push(`--c-${v(k)}:${c.hex}`);
  for (const [k, s] of Object.entries(t.sizes)) {
    if (k === 'fontSizes') for (const [fk, fv] of Object.entries(s)) base.push(`--fs-${fk}:${sc(fv)}`);
    else base.push(`--s-${k}:${sc(s.value)}`);
  }
  const uiFamily = t.fonts.ui.family;
  for (const [k, f] of Object.entries(t.fonts)) {
    base.push(`--f-${k}:${f.family === 'ui' ? uiFamily : f.family}`);
    base.push(`--fs-${k}:${sc(f.size)}`);
    base.push(`--fw-${k}:${f.weight}`);
  }
  const theme = (name) => Object.entries(t[name] ?? {}).map(([k, c]) => `--c-${v(k)}:${c.hex}`).join(';');
  return [
    `/* generated by build/tokens.mjs from ui-tokens.json ${t.version} (${t.generated}); do not edit */`,
    `:root,[data-theme="grey"]{${base.join(';')};color-scheme:light}`,
    `[data-theme="dark"]{${theme('colorsDarkDerived')};color-scheme:dark}`,
    `[data-theme="print"]{${theme('colorsPrintDerived')};color-scheme:light}`,
  ].join('\n');
}

/** Flat map of token → hex per theme, for the PT-09 look check. */
export function tokenTable(path) {
  const t = JSON.parse(readFileSync(path, 'utf8'));
  const grey = Object.fromEntries(Object.entries(t.colors).map(([k, c]) => [k, c.hex]));
  const dark = { ...grey, ...Object.fromEntries(Object.entries(t.colorsDarkDerived).map(([k, c]) => [k, c.hex])) };
  const print = { ...grey, ...Object.fromEntries(Object.entries(t.colorsPrintDerived ?? {}).map(([k, c]) => [k, c.hex])) };
  return { grey, dark, print, sizes: t.sizes };
}
