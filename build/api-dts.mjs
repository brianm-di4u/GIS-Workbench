// The typed reference of the automation API (REQ-GAP-01): docs/api/gisworkbench-api-<major>.d.ts,
// generated from app/src/automation/v2-spec.js so the reference and the API cannot drift.
//
//   node build/api-dts.mjs           write the file
//   node build/api-dts.mjs --check   exit 1 when the committed file differs (the unit test does this too)

import { writeFileSync, readFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';
import { METHODS, EVENTS, TYPES, API_VERSION, mcpName } from '../app/src/automation/v2-spec.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
// Named for the API's major version (REG-179), so the file and the version cannot disagree. The
// runtime namespace stays gisworkbench.api.v2.
export const DTS_PATH = join(root, 'docs', 'api', `gisworkbench-api-${API_VERSION.split('.')[0]}.d.ts`);
// The name before API 3.0.0, kept for one release as a file that only points to the new one; it is
// removed in the release after 2.7.2.
export const ALIAS_PATH = join(root, 'docs', 'api', 'gisworkbench-api-v2.d.ts');

/** The alias file's text. */
export function aliasText() {
  const target = basename(DTS_PATH);
  return [
    `// Renamed: the API ${API_VERSION} reference is now ${target}. This file only points there, and is`,
    '// removed in the release after 2.7.2. GENERATED by build/api-dts.mjs; do not edit by hand.',
    `/// <reference path="./${target}" />`,
    `export * from './${basename(target, '.d.ts')}';`,
    '',
  ].join('\n');
}

const pascal = (method) => method.split('.').map((p) => p[0].toUpperCase() + p.slice(1)).join('');
const lit = (v) => JSON.stringify(v);

/** A JSON schema (the spec's subset) as a TypeScript type. */
export function tsType(s) {
  if (!s) return 'unknown';
  if (Array.isArray(s.type)) return s.type.map((x) => tsType({ ...s, type: x })).join(' | ');
  if (s.enum) return s.enum.map(lit).join(' | ');
  switch (s.type) {
    case 'string':
      return 'string';
    case 'number':
    case 'integer':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'null':
      return 'null';
    case 'array':
      return s.items ? `${/[|&]/.test(tsType(s.items)) ? `(${tsType(s.items)})` : tsType(s.items)}[]` : 'unknown[]';
    case 'object':
      if (!s.properties || !Object.keys(s.properties).length) return 'Record<string, unknown>';
      return `{ ${Object.entries(s.properties).map(([k, p]) => `${k}${s.required?.includes(k) ? '' : '?'}: ${tsType(p)}`).join('; ')} }`;
    default:
      return 'unknown';
  }
}

const doc = (lines, indent = '') => [`${indent}/**`, ...lines.map((l) => `${indent} * ${l}`), `${indent} */`];

export function generate() {
  const out = [];
  out.push(`// GIS Workbench automation API ${API_VERSION}: typed reference (REQ-GAP-01). In the page it is gisworkbench.api.v2.`);
  out.push('// GENERATED by build/api-dts.mjs from app/src/automation/v2-spec.js; do not edit by hand.');
  out.push(`// API version ${API_VERSION} (semantic; independent of the app version). v1 (gisworkbench.api, api: 1) is unchanged.`);
  out.push('//');
  out.push('// In the page: `const v2 = gisworkbench.api.v2;` then `await v2.layers.list()` or `await v2.call("layers.list", {})`.');
  out.push('// Over MCP: each method that takes JSON is the tool gw2_<method with dots as underscores> (its _meta names the method);');
  out.push('// methods that change the project become proposals the analyst accepts. Results are English developer text.');
  out.push('');
  out.push(`export type ApiVersionString = ${lit(API_VERSION)};`);
  out.push('');
  for (const [name, def] of Object.entries(TYPES)) out.push(`export type ${name} = ${def};`);
  out.push('');
  out.push('// ---- parameters ----');
  for (const [method, m] of Object.entries(METHODS)) {
    const props = m.params.properties ?? {};
    out.push(...doc([`Parameters of \`${method}\`.`]));
    if (!Object.keys(props).length) {
      out.push(`export type ${pascal(method)}Params = Record<string, never>;`);
      continue;
    }
    out.push(`export interface ${pascal(method)}Params {`);
    for (const [k, p] of Object.entries(props)) {
      if (p.description) out.push(...doc([p.description], '  '));
      const t = m.files && (k === 'files' || k === 'model') ? (k === 'files' ? 'File[]' : 'File') : tsType(p);
      out.push(`  ${k}${m.params.required?.includes(k) ? '' : '?'}: ${t};`);
    }
    out.push('}');
  }
  out.push('');
  out.push('/** Every method: its parameters and result. */');
  out.push('export interface Methods {');
  for (const [method, m] of Object.entries(METHODS)) out.push(`  ${lit(method)}: { params: ${pascal(method)}Params; result: ${m.returns} };`);
  out.push('}');
  out.push('export type MethodName = keyof Methods;');
  out.push('');
  out.push('/** Events of on(type, fn) and events.recent. */');
  out.push('export interface EventMap {');
  for (const [k, e] of Object.entries(EVENTS)) {
    out.push(...doc([e.summary], '  '));
    out.push(`  ${k}: ${e.type};`);
  }
  out.push('}');
  out.push('export type EventName = keyof EventMap;');
  out.push('');
  // Nested namespaces.
  const tree = {};
  for (const method of Object.keys(METHODS)) {
    const parts = method.split('.');
    let n = tree;
    for (const p of parts.slice(0, -1)) n = n[p] ??= {};
    n[parts.at(-1)] = method;
  }
  const emitNs = (node, indent) => {
    for (const [k, v] of Object.entries(node)) {
      if (typeof v === 'string') {
        const m = METHODS[v];
        const req = (m.params.required ?? []).length > 0;
        const tags = [m.summary, '', `@since ${m.since}`, m.readOnly ? 'Read-only.' : 'Changes the project (one undo step); over MCP it is a proposal.', mcpName(v) ? `MCP tool: ${mcpName(v)}` : 'JavaScript only (takes File objects).'];
        if (m.dialog) tags.push('May open a dialog.');
        out.push(...doc(tags, indent));
        out.push(`${indent}${k}(params${req ? '' : '?'}: ${pascal(v)}Params): Promise<${m.returns}>;`);
      } else {
        out.push(`${indent}readonly ${k}: {`);
        emitNs(v, `${indent}  `);
        out.push(`${indent}};`);
      }
    }
  };
  out.push('/** gisworkbench.api.v2 */');
  out.push('export interface GisWorkbenchApiV2 {');
  out.push('  /** The API version, semantic. */');
  out.push('  readonly version: ApiVersionString;');
  out.push('  /** Call a method by name; the parameters are checked against its schema. */');
  out.push('  call<M extends MethodName>(method: M, params?: Methods[M]["params"]): Promise<Methods[M]["result"]>;');
  out.push('  /** Listen to an event; returns a function that stops listening. */');
  out.push('  on<E extends EventName>(type: E, fn: (e: EventMap[E]) => void): () => void;');
  out.push('  off<E extends EventName>(type: E, fn: (e: EventMap[E]) => void): void;');
  out.push('  /** The method names. */');
  out.push('  methods(): MethodName[];');
  emitNs(tree, '  ');
  out.push('}');
  out.push('');
  out.push('/** gisworkbench.api (v1, unchanged) with v2 beside it. */');
  out.push('export interface GisWorkbenchApi {');
  out.push('  version(): { version: string | null; build: string | null; api: 1 };');
  out.push('  help(): string[];');
  out.push('  readonly v2: GisWorkbenchApiV2;');
  out.push('  [v1method: string]: unknown;');
  out.push('}');
  out.push('');
  out.push('declare global {');
  out.push('  interface Window {');
  out.push('    gisworkbench: { api: GisWorkbenchApi };');
  out.push('  }');
  out.push('}');
  out.push('');
  return `${out.join('\n')}`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const want = [[DTS_PATH, generate()], [ALIAS_PATH, aliasText()]];
  if (process.argv.includes('--check')) {
    for (const [path, text] of want) {
      const cur = existsSync(path) ? readFileSync(path, 'utf8').replace(/\r\n/g, '\n') : '';
      if (cur !== text) {
        console.error(`${path} is out of date: run node build/api-dts.mjs`);
        process.exit(1);
      }
    }
    console.log(`api ${API_VERSION} reference is current`);
  } else {
    mkdirSync(dirname(DTS_PATH), { recursive: true });
    for (const [path, text] of want) writeFileSync(path, text);
    console.log(`wrote ${DTS_PATH} (${Object.keys(METHODS).length} methods) and its alias`);
  }
}
