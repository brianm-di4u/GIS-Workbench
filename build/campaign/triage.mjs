// Triage of the c50 format × function cross: aggregates the per-file records of one or more runs
// (reports/campaign/results/<run>/c50-*.json; a later run's cells of the same file win) into
// clustered findings, a format-key × command-group table and the slowest cells.
//   node build/campaign/triage.mjs cx1 [cx2 …] [--project=chrome] [--out=docs/validation/TE-cross-report.md]
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { REPO } from './corpus-lib.mjs';
import { isRefusal } from './verdict.mjs';

const args = process.argv.slice(2);
const runs = args.filter((a) => !a.startsWith('--'));
const opt = (k, d) => args.find((a) => a.startsWith(`--${k}=`))?.slice(k.length + 3) ?? d;
const project = opt('project', 'chrome');
const outMd = join(REPO, opt('out', 'docs/validation/TE-cross-report.md'));
if (!runs.length) throw new Error('usage: triage.mjs <run> [run…]');

const recs = new Map();
for (const run of runs) {
  const dir = join(REPO, 'reports/campaign/results', run);
  if (!existsSync(dir)) continue;
  for (const n of readdirSync(dir).filter((x) => x.startsWith(`c50-${project}-`) && x.endsWith('.json'))) {
    const r = JSON.parse(readFileSync(join(dir, n), 'utf8'));
    // A re-run (NVMe copies, a later build) may hold only the cells it re-tested: those cells win, the
    // file's other cells stay as first recorded.
    const prev = recs.get(r.key);
    recs.set(r.key, prev ? { ...prev, ...r, applicable: prev.applicable ?? r.applicable, cells: { ...prev.cells, ...r.cells }, run: `${prev.run}+${run}` } : { ...r, run });
  }
}

const BAD = new Set(['fail', 'timeout', 'crash']);
const verdicts = {};
const cells = [];
for (const r of recs.values()) for (const [id, c] of Object.entries(r.cells ?? {})) {
  // Records written before the 'refused' verdict existed: re-derive it from the message.
  if (c.verdict === 'fail' && c.why && isRefusal(c.why.split(' | '))) c.verdict = 'refused';
  verdicts[c.verdict] = (verdicts[c.verdict] ?? 0) + 1;
  cells.push({ r, id, c });
}
// One signature per defect: the command group, the verdict and the message with its numbers, paths,
// quoted names and file names taken out.
const norm = (s) => String(s ?? '')
  .replace(/[A-Za-z]:[\\/][^\s'"]+|\/[\w./-]+\.\w+/g, '<path>')
  .replace(/"[^"]*"|'[^']*'|«[^»]*»/g, '<q>')
  .replace(/\b[\w-]+\.(tif|tiff|ntf|nitf|nsf|las|laz|json|geojson|ts|mpg|jp2|png|jpg|kml|kmz|gpkg|shp|zip|h5|nc|hdr|img)\b/gi, '<file>')
  .replace(/\d+(\.\d+)?/g, 'N')
  .slice(0, 160);
const clusters = new Map();
for (const { r, id, c } of cells.filter((x) => BAD.has(x.c.verdict))) {
  const sig = `${c.verdict} | ${id.split('.')[0]} | ${norm(c.why)}`;
  const k = clusters.get(sig) ?? clusters.set(sig, { sig, verdict: c.verdict, why: c.why, cmds: new Set(), files: [], keys: new Set() }).get(sig);
  k.cmds.add(id);
  k.files.push(`${r.item}/${r.file}`);
  for (const fk of r.keys ?? []) k.keys.add(fk);
}
const sorted = [...clusters.values()].sort((a, b) => b.files.length - a.files.length);
// Named refusals (an error toast in words): reviewed for whether the command should have been offered.
const refusals = new Map();
for (const { r, id, c } of cells.filter((x) => x.c.verdict === 'refused')) {
  const sig = `${id} | ${norm(c.why)}`;
  const k = refusals.get(sig) ?? refusals.set(sig, { id, why: c.why, files: [] }).get(sig);
  k.files.push(`${r.item}/${r.file}`);
}

// Format key × command group: cells passing / all (non-silent, non-skip).
const group = (id) => id.split('.')[0];
const heat = new Map();
for (const { r, id, c } of cells) for (const fk of r.keys?.length ? r.keys : [`area:${r.area}`]) {
  const row = heat.get(fk) ?? heat.set(fk, new Map()).get(fk);
  const g = row.get(group(id)) ?? row.set(group(id), { ok: 0, bad: 0 }).get(group(id));
  if (BAD.has(c.verdict)) g.bad++;
  else g.ok++;
}
const groups = [...new Set(cells.map((x) => group(x.id)))].sort();

const files = [...recs.values()];
const refused = files.filter((r) => r.open?.refused).length;
const incomplete = files.filter((r) => !r.done);
const slow = cells.filter((x) => x.c.ms).sort((a, b) => b.c.ms - a.c.ms).slice(0, 40);
const silent = new Map();
for (const { id, c } of cells) if (c.verdict === 'silent') silent.set(id, (silent.get(id) ?? 0) + 1);
const heapGrowth = files.map((r) => {
  const hs = Object.values(r.cells ?? {}).map((c) => c.heapMB).filter((x) => x != null);
  return { key: r.key, open: r.open?.heapMB, max: hs.length ? Math.max(...hs) : null, last: hs.at(-1) ?? null };
}).filter((x) => x.open != null && x.last != null).sort((a, b) => (b.last - b.open) - (a.last - a.open)).slice(0, 15);

const L = [];
L.push(`# T&E format × function cross: ${runs.join(', ')} (${project})`, '');
L.push(`Generated by \`build/campaign/triage.mjs\` on ${new Date().toISOString().slice(0, 16)}Z from \`tests/campaign/c50-cross.spec.js\` records.`, '');
L.push(`- Files: ${files.length} (${refused} refused or unopenable, crossed by c01 only; ${incomplete.length} incomplete).`);
L.push(`- Cells: ${cells.length}. ${Object.entries(verdicts).sort((a, b) => b[1] - a[1]).map(([v, n]) => `${v} ${n}`).join(', ')}.`);
L.push(`- Defect clusters: ${sorted.length}.`, '');
L.push('## Defect clusters', '', '| # | Verdict | Commands | Files | Format keys | Message (first) | Example |', '|---|---|---|---|---|---|---|');
sorted.forEach((k, i) => L.push(`| ${i + 1} | ${k.verdict} | ${[...k.cmds].slice(0, 6).join(', ')}${k.cmds.size > 6 ? ` +${k.cmds.size - 6}` : ''} | ${k.files.length} | ${[...k.keys].slice(0, 4).join(', ')} | ${String(k.why ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ').slice(0, 220)} | ${k.files[0]} |`));
L.push('', '## Named refusals (review: should the command have been offered?)', '', '| Command | Files | Message | Example |', '|---|---|---|---|');
for (const k of [...refusals.values()].sort((a, b) => b.files.length - a.files.length)) L.push(`| ${k.id} | ${k.files.length} | ${String(k.why).replace(/\|/g, '\\|').slice(0, 200)} | ${k.files[0]} |`);
L.push('', '## Silent commands (ran, but no state change, dialog, download or message)', '', [...silent].sort((a, b) => b[1] - a[1]).map(([id, n]) => `${id} (${n})`).join(', ') || 'None.', '');
L.push('## Slowest cells', '', '| Command | File | s | Outcome |', '|---|---|---|---|');
for (const { r, id, c } of slow) L.push(`| ${id} | ${r.item}/${r.file} | ${(c.ms / 1000).toFixed(1)} | ${c.verdict} |`);
L.push('', '## Heap growth over a file’s commands (MB)', '', '| File | After open | Max | Last |', '|---|---|---|---|');
for (const h of heapGrowth) L.push(`| ${h.key} | ${h.open} | ${h.max} | ${h.last} |`);
L.push('', '## Format key × command group (passing / failing cells)', '', `| Key | ${groups.join(' | ')} |`, `|---|${groups.map(() => '---').join('|')}|`);
for (const [fk, row] of [...heat].sort()) L.push(`| ${fk} | ${groups.map((g) => (row.get(g) ? `${row.get(g).ok}${row.get(g).bad ? `/**${row.get(g).bad}**` : ''}` : '')).join(' | ')} |`);
if (incomplete.length) L.push('', '## Incomplete files', '', ...incomplete.map((r) => `- ${r.key}: ${r.crashed ?? 'not finished'}`));
writeFileSync(outMd, L.join('\n') + '\n');
writeFileSync(join(REPO, 'reports/campaign', `cross-${runs.at(-1)}-${project}.json`), JSON.stringify({ runs, project, files: files.length, refused, cells: cells.length, verdicts, clusters: sorted.map((k) => ({ ...k, cmds: [...k.cmds], keys: [...k.keys] })) }, null, 1));
console.log(`${files.length} files, ${cells.length} cells`, verdicts, `${sorted.length} clusters → ${outMd}`);
