def centre_chip(path, size, bands=None):
    ds = gdal.Open(str(path))
    w, h = min(size, ds.RasterXSize), min(size, ds.RasterYSize)
    return [(ds.RasterXSize - w) // 2, (ds.RasterYSize - h) // 2, w, h], bands or list(range(1, ds.RasterCount + 1))


def world_file(tif_like, path):
    """Six-line world file (centre of the upper-left pixel) plus an ESRI .prj."""
    ds = gdal.Open(str(tif_like))
    a, b, c, d, e, f = ds.GetGeoTransform()
    path.write_text('\n'.join(f'{v:.10f}' for v in (b, e, c, f, a + b / 2 + c / 2, d + e / 2 + f / 2)) + '\n')
    s = osr.SpatialReference(wkt=ds.GetProjection())
    s.MorphToESRI()
    path.with_suffix('.prj').write_text(s.ExportToWkt())


