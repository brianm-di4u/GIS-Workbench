def _sicd_corners(ds):
    for x in ds.GetMetadata('xml:DES') or []:
        if 'urn:SICD' in x:
            import re
            pts = re.findall(r'<(?:\w+:)?ICP index="(\d):\w+">\s*<(?:\w+:)?Lat>([-\d.eE+]+)</(?:\w+:)?Lat>\s*<(?:\w+:)?Lon>([-\d.eE+]+)</(?:\w+:)?Lon>', x)
            return {int(i): (float(la), float(lo)) for i, la, lo in pts}
    return {}


def sar_complex_slc():
    iid = 'derived-sar-complex-slc'
    d = outdir(iid)
    files, recipe = [], []
    srcs = (('umbra', src('umbra-bingham-20230925-full', 'umbra_20230925_SICD.nitf')), ('capella', src('capella-c13-sm-20240924', 'capella_C13_SM_SICD.ntf')),
            ('osml_umbra', src('sar-osml-sicd-sidd-chips', 'umbra-sicd121-chip1.ntf')))
    for tag, p in srcs:
        ds = gdal.Open(str(p))
        c = _sicd_corners(ds)
        n, m = ds.RasterYSize, ds.RasterXSize
        win = centre_chip(p, 2048)[0]
        # ICP 1..4 = FRFC, FRLC, LRLC, LRFC (row, col) in full-image pixels: GCPs re-expressed in chip pixels.
        rc = {1: (0, 0), 2: (0, m - 1), 3: (n - 1, m - 1), 4: (n - 1, 0)}
        gcps = [gdal.GCP(c[i][1], c[i][0], 0, rc[i][1] - win[0], rc[i][0] - win[1]) for i in sorted(c)]
        for dt, name in ((gdal.GDT_CFloat32, 'cfloat32'), (gdal.GDT_CInt32, 'cint32'), (gdal.GDT_CInt16, 'cint16')):
            o = f'{tag}_slc_{name}.tif'
            gdal.Translate(str(d / o), ds, options=gdal.TranslateOptions(srcWin=win, outputType=dt, GCPs=gcps, outputSRS='EPSG:4326', creationOptions=['TILED=YES', 'COMPRESS=DEFLATE']))
            files.append((o, 'primary'))
            recipe.append(f'gdal_translate -ot {gdal.GetDataTypeName(dt)} -srcwin {" ".join(map(str, win))} -gcp ×4 (SICD GeoData ImageCorners) -a_srs EPSG:4326 {p.name} {o}')
