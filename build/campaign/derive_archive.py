def qmesh_geodetic():
    from pydelatin import Delatin
    from quantized_mesh_encoder import encode
    from quantized_mesh_encoder import WGS84
    iid = 'derived-qmesh-geodetic'
    d = outdir(iid)
    cop = gdal.Open(str(src(*COP)))
    wbm = gdal.Open(str(src('cop-dem-glo30-n39w106', 'Copernicus_DSM_COG_10_N39_00_W106_00_WBM.tif')))
    files, recipe = [], []
    variants = (('plain', {}), ('normals', {'normals': True}), ('watermask', {'watermask': True}))
    maxz = 9
    for tag, opt in variants:
        root = d / tag
        avail = []
        for z in range(maxz + 1):
            n = 2 ** z  # geodetic TMS: 2·2^z × 2^z tiles, 180/2^z degrees each
            size = 180 / n
            x0, x1 = int((-106 + 180) // size), int((-105 - 1e-9 + 180) // size)
            y0, y1 = int((39 + 90) // size), int((40 - 1e-9 + 90) // size)
            avail.append([{'startX': x0, 'endX': x1, 'startY': y0, 'endY': y1}])
            for x in range(x0, x1 + 1):
                for y in range(y0, y1 + 1):
                    w, s = -180 + x * size, -90 + y * size
                    e_, n_ = w + size, s + size
                    arr = gdal.Warp('', cop, options=gdal.WarpOptions(format='MEM', outputBounds=(w, s, e_, n_), width=65, height=65, resampleAlg='bilinear', dstNodata=0)).ReadAsArray().astype('float32')
                    tin = Delatin(arr, width=65, height=65, max_error=2.0)
                    verts, tris = tin.vertices, tin.triangles
                    lon = w + verts[:, 0] / 64 * (e_ - w)
                    lat = n_ - verts[:, 1] / 64 * (n_ - s)
                    pos = np.column_stack([lon, lat, verts[:, 2]]).astype('float32')
                    tris = tris.astype('uint32')
                    p = root / str(z) / str(x) / f'{y}.terrain'
                    p.parent.mkdir(parents=True, exist_ok=True)
                    ext = []
                    if opt.get('normals'):
                        from quantized_mesh_encoder.extensions import VertexNormalsExtension
                        ext.append(VertexNormalsExtension(positions=pos, indices=tris, ellipsoid=WGS84))
                    if opt.get('watermask'):
                        from quantized_mesh_encoder.extensions import WaterMaskExtension
                        m = gdal.Warp('', wbm, options=gdal.WarpOptions(format='MEM', outputBounds=(w, s, e_, n_), width=256, height=256)).ReadAsArray()
                        ext.append(WaterMaskExtension(data=np.where(m > 0, 255, 0).astype('uint8')))
                    with open(p, 'wb') as f:
                        encode(f, pos, tris, bounds=(w, s, e_, n_), sphere_method='bounding_box', ellipsoid=WGS84, extensions=ext)
                    files.append((f'{tag}/{z}/{x}/{y}.terrain', 'primary'))
        exts = {'normals': ['octvertexnormals'], 'watermask': ['watermask']}.get(tag, [])
        (root / 'layer.json').write_text(json.dumps({'tilejson': '2.1.0', 'name': f'cop-glo30-n39w106-{tag}', 'version': '1.0.0', 'format': 'quantized-mesh-1.0', 'scheme': 'tms',
                                                     'tiles': ['{z}/{x}/{y}.terrain?v={version}'], 'projection': 'EPSG:4326', 'bounds': [-106, 39, -105, 40], 'minzoom': 0, 'maxzoom': maxz,
                                                     'available': avail, 'extensions': exts}, indent=1))
        files.append((f'{tag}/layer.json', 'metadata'))
        recipe.append(f'Copernicus GLO-30 → 65² grid per geodetic TMS tile (z0–{maxz}) → pydelatin TIN → quantized-mesh-encoder{" + " + exts[0] if exts else ""}; layer.json EPSG:4326')
    return entry(iid, 'dem', 'Quantized-mesh 1.0 terrain in EPSG:4326 (geodetic TMS, z0–9, Colorado N39W106): plain, octvertexnormals, watermask', [COP[0]],
                 'Copernicus DEM licence (free use with attribution)', '© DLR e.V. 2010-2014 and © Airbus Defence and Space GmbH 2014-2018 provided under COPERNICUS by the European Union and ESA',
                 'Cesium quantized-mesh 1.0 + layer.json', 'Uncompressed .terrain files; serve with the test server for 3d.qmesh', files, recipe, ['qmesh.tile', 'qmesh.geodetic'], ['3d.qmesh', 'dem'],
                 notes='The existing heremaps tiles are EPSG:3857 (refused, IMP-20); these are the geodetic layout the app reads.')


