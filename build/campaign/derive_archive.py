def tci_path():
    it = item(TCI[0])
    return next(common.item_dir(it).joinpath(*f['name'].split('/')) for f in it['files'] if f['name'].endswith('_TCI.jp2'))


def rgb_chips(d, size=1024):
    """Three real 8-bit RGB chips (NAIP 0.6 m, Sentinel-2 TCI 10 m, WorldView-3 visual 0.3 m) as GeoTIFF."""
    out = []
    for tag, p in (('naip', src(*NAIP)), ('s2tci', tci_path()), ('wv3vis', src(*MAXAR_VIS))):
        win, _ = centre_chip(p, size)
        t = d / f'_{tag}_chip.tif'
        gdal.Translate(str(t), str(p), options=gdal.TranslateOptions(srcWin=win, bandList=[1, 2, 3]))
        out.append((tag, t, win, p.name))
    return out


def pictures_worldfile():
    iid = 'derived-pictures-worldfile'
    d = outdir(iid)
    files, recipe = [], []
    wext = {'JPEG': ('jpg', 'jgw'), 'PNG': ('png', 'pgw'), 'GIF': ('gif', 'gfw'), 'BMP': ('bmp', 'bpw'), 'WEBP': ('webp', 'wld')}
    for tag, chip, win, name in rgb_chips(d):
        for drv, (e, w) in wext.items():
            o = d / f'{tag}.{e}'
            bands = [1] if drv == 'GIF' else [1, 2, 3]
            opts = ['QUALITY=90'] if drv in ('JPEG', 'WEBP') else []
            gdal.Translate(str(o), str(chip), options=gdal.TranslateOptions(format=drv, bandList=bands, creationOptions=opts))
            world_file(chip, o.with_suffix(f'.{w}'))
            files += [(o.name, 'primary'), (o.with_suffix(f'.{w}').name, 'sidecar'), (o.with_suffix('.prj').name, 'sidecar')]
            recipe.append(f'gdal_translate -of {drv} -srcwin {" ".join(map(str, win))} {" ".join("-b " + str(b) for b in bands)} {name} {o.name} (+ .{w} world file, .prj)')
        chip.unlink()
    return entry(iid, 'eo', 'JPEG/PNG/GIF/BMP/WebP chips with world files and .prj (NAIP, Sentinel-2 TCI, WorldView-3 visual)', [NAIP[0], TCI[0], MAXAR_VIS[0]], LIC_MIX, ATT_MIX,
                 'JPEG/PNG/GIF/BMP/WebP + world file', '1024² chips; GIF is band 1 only; world files .jgw/.pgw/.gfw/.bpw/.wld', files, recipe,
                 ['img.jpg', 'img.jpg.world', 'img.png', 'img.png.world', 'img.gif.world', 'img.bmp.world', 'img.webp.world'], ['ingest', 'display'])


def jp2_variants():
    iid = 'derived-jp2-variants'
    d = outdir(iid)
    files, recipe = [], []
    for tag, chip, win, name in rgb_chips(d):
        for kind, opts in (('geojp2', ['GMLJP2=NO', 'GeoJP2=YES']), ('gmljp2', ['GMLJP2=YES', 'GeoJP2=NO'])):
            o = d / f'{tag}_{kind}.jp2'
            gdal.Translate(str(o), str(chip), options=gdal.TranslateOptions(format='JP2OpenJPEG', creationOptions=opts + ['QUALITY=50', 'RESOLUTIONS=5']))
            files.append((o.name, 'primary'))
            recipe.append(f'gdal_translate -of JP2OpenJPEG {" ".join("-co " + x for x in opts)} -srcwin {" ".join(map(str, win))} {name} {o.name}')
        o = d / f'{tag}_codestream.j2k'
        gdal.Translate(str(o), str(chip), options=gdal.TranslateOptions(format='JP2OpenJPEG', creationOptions=['CODEC=J2K', 'QUALITY=50']))
        world_file(chip, o.with_suffix('.j2w'))
        files += [(o.name, 'primary'), (o.with_suffix('.j2w').name, 'sidecar'), (o.with_suffix('.prj').name, 'sidecar')]
        recipe.append(f'gdal_translate -of JP2OpenJPEG -co CODEC=J2K {name} {o.name} (+ .j2w)')
        ppm = d / f'_{tag}.ppm'
        gdal.Translate(str(ppm), str(chip), options=gdal.TranslateOptions(format='PNM'))
        o = d / f'{tag}_htj2k.j2c'
        recipe.append(run([BIN / 'ojph_compress.exe', '-i', ppm, '-o', o, '-num_decomps', '5', '-reversible', 'true']))
        world_file(chip, o.with_suffix('.j2w'))
        files += [(o.name, 'primary'), (o.with_suffix('.j2w').name, 'sidecar'), (o.with_suffix('.prj').name, 'sidecar')]
        ppm.unlink()
        chip.unlink()
    return entry(iid, 'eo', 'JPEG 2000 variants: GeoJP2-only, GMLJP2-only, raw J2K codestream + .j2w, HTJ2K (OpenJPH, reversible) + .j2w', [NAIP[0], TCI[0], MAXAR_VIS[0]], LIC_MIX, ATT_MIX,
                 'JPEG 2000 (JP2 / J2K / HTJ2K)', '1024² RGB chips from three sensors', files, recipe, ['jp2', 'jp2.geojp2', 'jp2.gmljp2', 'jp2.codestream', 'jp2.htj2k'], ['ingest', 'display'])


def gtiff_variants():
    """BigTIFF, big-endian, extra codec samples, GCP-georeferenced and RPC-tagged GeoTIFFs."""
    iid = 'derived-gtiff-variants'
    d = outdir(iid)
    files, recipe = [], []

    def tr(o, p, opts, **kw):
        gdal.Translate(str(d / o), str(p), options=gdal.TranslateOptions(creationOptions=opts, **kw))
        files.append((o, 'primary'))
        recipe.append(f'gdal_translate {" ".join("-co " + x for x in opts)} {kw.get("srcWin", "")} {p.name} {o}'.replace('  ', ' '))

    cop, ls4, naip = src(*COP), src(*LS_B4), src(*NAIP)
    tr('naip_bigtiff_tiled.tif', naip, ['BIGTIFF=YES', 'TILED=YES', 'COMPRESS=DEFLATE'], srcWin=centre_chip(naip, 4096)[0])
    tr('cop_dem_bigtiff_striped.tif', cop, ['BIGTIFF=YES', 'TILED=NO', 'COMPRESS=LZW', 'PREDICTOR=3'])
    tr('landsat_b4_bigtiff_bigendian.tif', ls4, ['BIGTIFF=YES', 'ENDIANNESS=BIG', 'TILED=YES', 'COMPRESS=ZSTD'])
    tr('cop_dem_bigendian.tif', cop, ['ENDIANNESS=BIG', 'TILED=YES', 'COMPRESS=DEFLATE', 'PREDICTOR=3'])
    tr('naip_bigendian_striped.tif', naip, ['ENDIANNESS=BIG', 'COMPRESS=PACKBITS'], srcWin=centre_chip(naip, 2048)[0])
    for tag, chip, win, name in rgb_chips(d, 2048):
        if tag == 'naip':  # NAIP is already in derived-gtiff-codec-matrix
            chip.unlink()
            continue
        for comp, extra in (('LZW', ['PREDICTOR=2']), ('PACKBITS', []), ('JPEG', ['PHOTOMETRIC=YCBCR', 'JPEG_QUALITY=85']), ('WEBP', ['WEBP_LEVEL=85']),
                            ('ZSTD', ['PREDICTOR=2']), ('LERC', ['MAX_Z_ERROR=0'])):
            o = f'{tag}_{comp.lower()}.tif'
            gdal.Translate(str(d / o), str(chip), options=gdal.TranslateOptions(creationOptions=['TILED=YES', f'COMPRESS={comp}', *extra]))
            files.append((o, 'primary'))
            recipe.append(f'gdal_translate -srcwin {" ".join(map(str, win))} -b 1 -b 2 -b 3 -co TILED=YES -co COMPRESS={comp} {" ".join("-co " + x for x in extra)} {name} {o}')
        chip.unlink()
    # GCP-only georeferencing: 16 GCPs sampled from the real geotransform, then the transform removed.
    for p, o in ((naip, 'naip_gcps.tif'), (ls4, 'landsat_b4_gcps.tif'), (cop, 'cop_dem_gcps.tif')):
        ds = gdal.Open(str(p))
        win = centre_chip(p, 1024)[0]
        gt = ds.GetGeoTransform()
        gcps = []
        for i in range(4):
            for j in range(4):
                px, ln = win[0] + j * (win[2] - 1) / 3, win[1] + i * (win[3] - 1) / 3
                gcps.append(gdal.GCP(gt[0] + px * gt[1] + ln * gt[2], gt[3] + px * gt[4] + ln * gt[5], 0, px - win[0], ln - win[1]))
        gdal.Translate(str(d / o), ds, options=gdal.TranslateOptions(srcWin=win, GCPs=gcps, outputSRS=ds.GetProjection(), creationOptions=['COMPRESS=DEFLATE']))
        files.append((o, 'primary'))
        recipe.append(f'gdal_translate -srcwin {" ".join(map(str, win))} -gcp ×16 (from the source geotransform) -a_srs <source> {p.name} {o}')
    # RPC in TIFF tag 50844 from the IARPA MVS WV3 NITF chips (real RPC00B).
    mvs = item('rs-nitf-wv3-mvs-stereo-chips')
    for f in [f for f in mvs['files'] if f['name'].lower().endswith('.ntf')][:3]:
        p = common.item_dir(mvs) / f['name']
        o = f'mvs_{Path(f["name"]).stem}_rpc.tif'
        gdal.Translate(str(d / o), str(p), options=gdal.TranslateOptions(format='GTiff', creationOptions=['COMPRESS=DEFLATE', 'TILED=YES']))
        files.append((o, 'primary'))
        recipe.append(f'gdal_translate -of GTiff {p.name} {o} (RPC00B → RPCCoefficientTag)')
    return entry(iid, 'eo', 'GeoTIFF variants: BigTIFF (tiled/striped), big-endian, extra codec samples (S2 TCI, WV3), GCP-only and RPC-tag georeferencing',
                 [NAIP[0], COP[0], LS_B4[0], TCI[0], MAXAR_VIS[0], 'rs-nitf-wv3-mvs-stereo-chips'], LIC_MIX + '; IARPA MVS benchmark (JHU/APL)', ATT_MIX + '; IARPA MVS 3D Mapping benchmark',
                 'GeoTIFF / BigTIFF', 'BIGTIFF=YES, ENDIANNESS=BIG, LZW/PACKBITS/JPEG/WEBP/ZSTD/LERC, 16 GCPs, RPC tag', files, recipe,
                 ['gtiff.bigtiff', 'gtiff.bigendian', 'gtiff.codec.lzw', 'gtiff.codec.packbits', 'gtiff.codec.jpeg', 'gtiff.codec.webp', 'gtiff.codec.zstd', 'gtiff.codec.lerc', 'georef.gcps', 'rpc.gtiff'],
                 ['ingest', 'display', 'sensor-model'])


def envi_variants():
    iid = 'derived-envi-variants'
    d = outdir(iid)
    files, recipe = [], []
    srcs = (('enmap', src('enmap-potsdam-l2a-subset', 'enmap_potsdam.tif'), None), ('indianpines', src('rs-hsi-indian-pines', '19920612_AVIRIS_IndianPine_Site3.tif'), None),
            ('landsat_sr', None, [src('landsat8-c2-l2sp-044034-20240820', f'LC08_L2SP_044034_20240820_20240830_02_T1_SR_B{b}.TIF') for b in range(1, 8)]))
    for tag, p, stack in srcs:
        if stack:
            vrt = d / '_stack.vrt'
            gdal.BuildVRT(str(vrt), [str(x) for x in stack], options=gdal.BuildVRTOptions(separate=True))
            win = centre_chip(vrt, 1024)[0]
            p = d / '_stack.tif'
            gdal.Translate(str(p), str(vrt), options=gdal.TranslateOptions(srcWin=win))
            vrt.unlink()
        for il in ('BIL', 'BIP'):
            o = d / f'{tag}_{il.lower()}.img'
            gdal.Translate(str(o), str(p), options=gdal.TranslateOptions(format='ENVI', creationOptions=[f'INTERLEAVE={il}']))
            files += [(o.name, 'primary'), (o.with_suffix('.hdr').name, 'sidecar')]
            recipe.append(f'gdal_translate -of ENVI -co INTERLEAVE={il} {p.name} {o.name}')
        # Big-endian BSQ: GDAL writes native order, so swap the bytes and set 'byte order = 1'.
        o = d / f'{tag}_bsq_bigendian.img'
        gdal.Translate(str(o), str(p), options=gdal.TranslateOptions(format='ENVI', creationOptions=['INTERLEAVE=BSQ']))
        hdr = o.with_suffix('.hdr')
        ds = gdal.Open(str(o))
        dt = {1: 'u1', 2: '<u2', 3: '<i2', 4: '<u4', 5: '<i4', 6: '<f4', 7: '<f8'}[ds.GetRasterBand(1).DataType]
        ds = None
        a = np.fromfile(o, dtype=dt)
        a.astype(a.dtype.newbyteorder('>')).tofile(o)
        t = hdr.read_text()
        hdr.write_text(t.replace('byte order = 0', 'byte order = 1'))
        files += [(o.name, 'primary'), (hdr.name, 'sidecar')]
        recipe.append(f'gdal_translate -of ENVI -co INTERLEAVE=BSQ {p.name} {o.name}; byte-swap samples, header byte order = 1')
        if stack:
            p.unlink()
    for x in d.glob('*.aux.xml'):
        x.unlink()
    return entry(iid, 'hsi', 'ENVI raw variants: BIL, BIP and big-endian BSQ (EnMAP 224-band, AVIRIS Indian Pines 220-band, Landsat 8 SR 7-band)',
                 ['enmap-potsdam-l2a-subset', 'rs-hsi-indian-pines', 'landsat8-c2-l2sp-044034-20240820'],
                 'EnMAP data © DLR (EnMAP-Box GPL-3.0 redistribution); Indian Pines CC0; Landsat public domain → ' + TEST_ONLY, 'DLR EnMAP; Purdue (Baumgardner, Biehl, Landgrebe); USGS Landsat',
                 'ENVI raw + .hdr', 'INTERLEAVE=BIL/BIP; byte order = 1', files, recipe, ['envi', 'envi.bil', 'envi.bip', 'envi.bigendian', 'envi.mapinfo'], ['ingest', 'msi'])


