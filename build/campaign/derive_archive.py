def item(i):
    return next(x for x in common.manifest()['items'] if x['id'] == i)


def src(i, name):
    p = common.item_dir(item(i)).joinpath(*name.split('/'))
    if not p.is_file():
        raise FileNotFoundError(p)
    return p


def outdir(iid):
    d = common.CORPUS / iid
    d.mkdir(parents=True, exist_ok=True)
    return d


def run(cmd, **kw):
    subprocess.run([str(c) for c in cmd], check=True, capture_output=True, **kw)
    return ' '.join(Path(str(c)).name if Path(str(c)).is_absolute() else str(c) for c in cmd)


