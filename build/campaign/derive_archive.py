def _geoid18(lat, lon):
    """GEOID18 undulation (m) by bilinear sampling of the PROJ grid us_noaa_g2018u0.tif."""
    g = _geoid18.ds = getattr(_geoid18, 'ds', None) or gdal.Open(str(src('support-proj-grids-geoid', 'us_noaa_g2018u0.tif')))
    gt = g.GetGeoTransform()
    lon = lon % 360 if gt[0] > 0 else lon  # the PROJ grid uses 0–360° east longitudes
    x, y = (lon - gt[0]) / gt[1] - 0.5, (lat - gt[3]) / gt[5] - 0.5
    i, j = int(math.floor(x)), int(math.floor(y))
    a = g.GetRasterBand(1).ReadAsArray(i, j, 2, 2).astype('float64')
    fx, fy = x - i, y - j
    return a[0, 0] * (1 - fx) * (1 - fy) + a[0, 1] * fx * (1 - fy) + a[1, 0] * (1 - fx) * fy + a[1, 1] * fx * fy


