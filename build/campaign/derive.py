"""Derived test files made from real corpus data with the reference tools (GDAL, laspy), for
encodings no public sample covers: the GeoTIFF codec matrix and LAS point formats 5 and 9.
Every output records its source item and the exact command in TE-corpus/<id>/SOURCE.txt and is
registered in build/campaign/sources/derived.json (re-run make-corpus, then fetch --lock --verify).

    ../TE-tools/micromamba.exe run -n gw-te python -I build/campaign/derive.py
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent / 'oracles'))
import common  # noqa: E402
from osgeo import gdal  # noqa: E402

gdal.UseExceptions()
gdal.SetConfigOption('GDAL_PAM_ENABLED', 'NO')
OUT = common.HERE.parent / 'sources' / 'derived.json'


def item_by_id(i):
    return next(x for x in common.manifest()['items'] if x['id'] == i)


def gtiff_codecs():
    """One real 3-band 8-bit chip (NAIP) and one real float32 DEM chip (Copernicus) in every codec."""
    rgb = common.files(item_by_id('naip-ca-sfbay-2022'))[0] if any(x['id'] == 'naip-ca-sfbay-2022' for x in common.manifest()['items']) else None
    if rgb is None:
        rgb = next(p for it in common.manifest()['items'] if it['area'] == 'naip' for p in common.files(it))
    dem = common.files(item_by_id('cop-dem-glo30-n39w106'))[0]
    iid = 'derived-gtiff-codec-matrix'
    d = common.CORPUS / iid
    d.mkdir(parents=True, exist_ok=True)
    recipes = [
        ('rgb', rgb, 'NONE', []), ('rgb', rgb, 'LZW', ['PREDICTOR=2']), ('rgb', rgb, 'DEFLATE', ['PREDICTOR=2']),
        ('rgb', rgb, 'PACKBITS', []), ('rgb', rgb, 'JPEG', ['PHOTOMETRIC=YCBCR', 'JPEG_QUALITY=85']), ('rgb', rgb, 'WEBP', ['WEBP_LEVEL=85']),
        ('rgb', rgb, 'ZSTD', ['PREDICTOR=2']), ('rgb', rgb, 'LERC', ['MAX_Z_ERROR=0']), ('rgb', rgb, 'LERC_ZSTD', ['MAX_Z_ERROR=0']),
        ('dem', dem, 'DEFLATE', ['PREDICTOR=3']), ('dem', dem, 'LZW', ['PREDICTOR=3']), ('dem', dem, 'ZSTD', ['PREDICTOR=3']),
        ('dem', dem, 'LERC', ['MAX_Z_ERROR=0.01']), ('dem', dem, 'LERC_DEFLATE', ['MAX_Z_ERROR=0.01']),
    ]
    files, cmds = [], []
    for kind, src, comp, extra in recipes:
        name = f'{kind}_{comp.lower()}.tif'
        opts = ['TILED=YES', 'BLOCKXSIZE=256', 'BLOCKYSIZE=256', f'COMPRESS={comp}', *extra]
        srcwin = [0, 0, 1024, 1024] if kind == 'rgb' else [0, 0, 1200, 1200]
        bands = [1, 2, 3] if kind == 'rgb' else [1]
        gdal.Translate(str(d / name), str(src), options=gdal.TranslateOptions(creationOptions=opts, srcWin=srcwin, bandList=bands))
        cmds.append(f'gdal_translate -srcwin {" ".join(map(str, srcwin))} {" ".join("-b " + str(b) for b in bands)} {" ".join("-co " + o for o in opts)} {src.name} {name}')
        files.append({'name': name, 'url': None, 'role': 'primary'})
    return {
        'id': iid, 'area': 'eo', 'title': 'GeoTIFF codec matrix (tiled 256², 8-bit RGB from NAIP and float32 DEM from Copernicus GLO-30)',
        'source': 'Derived (GDAL) from corpus items', 'landing': 'build/campaign/derive.py', 'licence': 'Public domain (USDA NAIP) and Copernicus DEM licence (free use with attribution)',
        'attribution': 'USDA NAIP; © DLR e.V. 2010-2014 and © Airbus Defence and Space GmbH 2014-2018 provided under COPERNICUS by the European Union and ESA',
        'tier': 'A', 'origin': 'derived', 'format': 'GeoTIFF', 'profile': 'NONE/LZW/DEFLATE/PACKBITS/JPEG/WEBP/ZSTD/LERC/LERC_ZSTD/LERC_DEFLATE',
        'files': files, 'sign': None, 'derivation': '; '.join(cmds), 'notes': 'Generated by build/campaign/derive.py', 'feeds': ['ingest', 'display', 'dem'],
    }


def las_pdrf():
    """LAS 1.4 PDRF 5 and 9 (waveform-packet layouts no public sample covers) from Autzen."""
    import laspy
    import numpy as np
    src = next(p for p in common.files(item_by_id('rs-lidar-las-laz-copc')) if p.name == 'autzen_trim.las')
    iid = 'derived-las-pdrf-5-9'
    d = common.CORPUS / iid
    d.mkdir(parents=True, exist_ok=True)
    las = laspy.read(str(src))
    files = []
    for fmt, ver in ((5, '1.3'), (9, '1.4')):
        out = laspy.convert(las, point_format_id=fmt, file_version=ver)
        out.wavepacket_index = np.zeros(len(out.points), dtype=np.uint8)  # no waveform records: packets point nowhere
        name = f'autzen_pdrf{fmt}_las{ver.replace(".", "")}.las'
        out.write(str(d / name))
        files.append({'name': name, 'url': None, 'role': 'primary'})
    return {
        'id': iid, 'area': 'lidar', 'title': 'Autzen converted to LAS PDRF 5 (LAS 1.3) and PDRF 9 (LAS 1.4)', 'source': 'Derived (laspy) from rs-lidar-las-laz-copc',
        'landing': 'build/campaign/derive.py', 'licence': 'PDAL/laspy test data (BSD)', 'attribution': 'PDAL and laspy test data (Autzen Stadium, Oregon)',
        'tier': 'A', 'origin': 'derived', 'format': 'LAS', 'profile': 'PDRF 5, PDRF 9 (waveform packet fields, no waveform data)', 'files': files, 'sign': None,
        'derivation': 'laspy.convert(autzen_trim.las, point_format_id=5|9)', 'notes': 'Generated by build/campaign/derive.py', 'feeds': ['lidar', 'ingest'],
    }


def viewshed_truth():
    """S-15 / AT-18.2: a 1025² UTM crop of Copernicus GLO-30 (Colorado Front Range) and the
    gdal_viewshed result from its centre with the app's defaults (2 m observer, 1.8 m target,
    curvature/refraction -cc 0.87)."""
    import subprocess
    from pyproj import Transformer
    dem = common.files(item_by_id('cop-dem-glo30-n39w106'))[0]
    iid = 'derived-dem-utm13-viewshed'
    d = common.CORPUS / iid
    d.mkdir(parents=True, exist_ok=True)
    # 1025 × 30 m around 39.55 N, 105.55 W (mountain and valley mix).
    tr = Transformer.from_crs(4326, 32613, always_xy=True)
    cx, cy = tr.transform(-105.55, 39.55)
    half = 512 * 30 + 15
    out = d / 'dem_utm13_30m.tif'
    gdal.Warp(str(out), str(dem), options=gdal.WarpOptions(dstSRS='EPSG:32613', outputBounds=(cx - half, cy - half, cx + half, cy + half), xRes=30, yRes=30, resampleAlg='bilinear', creationOptions=['COMPRESS=DEFLATE', 'PREDICTOR=3', 'TILED=YES']))
    vs = d / 'viewshed_gdal.tif'
    cmd = ['gdal_viewshed', '-ox', str(cx), '-oy', str(cy), '-oz', '2', '-tz', '1.8', '-cc', '0.87', '-vv', '255', '-iv', '0', '-ov', '0', '-md', '0', str(out), str(vs)]
    subprocess.run(cmd, check=True, capture_output=True)
    lon, lat = Transformer.from_crs(32613, 4326, always_xy=True).transform(cx, cy)
    (d / 'viewshed_truth.json').write_text(json.dumps({'observer': {'lat': lat, 'lon': lon, 'x': cx, 'y': cy, 'epsg': 32613}, 'observerH': 2, 'targetH': 1.8, 'cc': 0.87, 'command': ' '.join(cmd)}, indent=1), encoding='utf-8')
    return {
        'id': iid, 'area': 'dem', 'title': 'Copernicus GLO-30 crop in UTM 13N (1025², 30 m) with the gdal_viewshed result from its centre',
        'source': 'Derived (GDAL) from cop-dem-glo30-n39w106', 'landing': 'build/campaign/derive.py', 'licence': 'Copernicus DEM licence (free use with attribution)',
        'attribution': '© DLR e.V. 2010-2014 and © Airbus Defence and Space GmbH 2014-2018 provided under COPERNICUS by the European Union and ESA',
        'tier': 'A', 'origin': 'derived', 'format': 'GeoTIFF', 'profile': 'float32 DEM + Byte viewshed (255 visible)',
        'files': [{'name': 'dem_utm13_30m.tif', 'url': None, 'role': 'primary'}, {'name': 'viewshed_gdal.tif', 'url': None, 'role': 'truth'}, {'name': 'viewshed_truth.json', 'url': None, 'role': 'truth'}],
        'sign': None, 'derivation': 'gdalwarp to EPSG:32613 30 m; ' + ' '.join(cmd), 'notes': 'Generated by build/campaign/derive.py', 'feeds': ['dem', 'los.viewshed'],
    }


if __name__ == '__main__':
    items = [gtiff_codecs(), las_pdrf(), viewshed_truth()]
    OUT.write_text(json.dumps(items, indent=1), encoding='utf-8')
    print(json.dumps([{'id': i['id'], 'files': [f['name'] for f in i['files']]} for i in items], indent=1))
